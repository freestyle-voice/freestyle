// Generates src/renderer/src/assets/jeb/manifest.json from the sprite strips
// in the same directory. Every sheet is a horizontal strip of uniform
// 96x96 frames, so the frame count is width / 96 read straight from the PNG
// header. Per-state playback metadata (fps, loop, impactFrame) is authored
// here — impactFrame is the synchronization contract between an animation
// and the OS action it decorates (the paste fires on the sword's hit frame).

const { readFileSync, writeFileSync, readdirSync } = require("node:fs");
const { join, basename } = require("node:path");

const JEB_DIR = join(
  __dirname,
  "..",
  "src",
  "renderer",
  "src",
  "assets",
  "jeb",
);
const FRAME = 96;

const STATES = {
  idle: { fps: 8, loop: true },
  walk: { fps: 10, loop: true },
  run: { fps: 14, loop: true },
  dash: { fps: 16, loop: true },
  "jump-start": { fps: 14, loop: false },
  jump: { fps: 10, loop: true },
  "jump-transition": { fps: 14, loop: false },
  "jump-fall": { fps: 10, loop: true },
  "wall-contact": { fps: 12, loop: false },
  "wall-slide": { fps: 10, loop: true },
  "wall-jump": { fps: 14, loop: false },
  climbing: { fps: 10, loop: true },
  "attack-1": { fps: 14, loop: false, impactFrame: 3 },
  "attack-2": { fps: 14, loop: false, impactFrame: 4 },
  "attack-3": { fps: 14, loop: false, impactFrame: 3 },
  "air-attack": { fps: 14, loop: false, impactFrame: 3 },
  "special-attack": { fps: 14, loop: false, impactFrame: 9 },
  throw: { fps: 14, loop: false, impactFrame: 5 },
  defend: { fps: 10, loop: false, holdLast: true },
  hurt: { fps: 10, loop: false },
  death: { fps: 10, loop: false, holdLast: true },
  healing: { fps: 10, loop: true },
  "healing-no-effect": { fps: 10, loop: true },
};

function pngWidth(path) {
  const buf = readFileSync(path);
  if (buf.readUInt32BE(12) !== 0x49484452) {
    throw new Error(`${path}: IHDR not where expected`);
  }
  return buf.readUInt32BE(16);
}

const manifest = { frameSize: FRAME, scale: 2, states: {} };

// Non-state assets living in the same directory (props, projectiles).
const EXTRAS = new Set(["shuriken"]);

for (const file of readdirSync(JEB_DIR).sort()) {
  if (!file.endsWith(".png")) continue;
  const name = basename(file, ".png");
  if (EXTRAS.has(name)) continue;
  const meta = STATES[name];
  if (!meta) throw new Error(`No state metadata for sheet ${file}`);
  const width = pngWidth(join(JEB_DIR, file));
  if (width % FRAME !== 0)
    throw new Error(`${file}: width ${width} not a multiple of ${FRAME}`);
  manifest.states[name] = { sheet: file, frames: width / FRAME, ...meta };
}

for (const name of Object.keys(STATES)) {
  if (!manifest.states[name])
    throw new Error(`Missing sheet for state ${name}`);
}

writeFileSync(
  join(JEB_DIR, "manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
);

const ts = `// Generated by scripts/pack-jeb-sprites.js — do not edit by hand.
import type { JebStateName } from "../../../../shared/jeb";

export interface JebStateMeta {
  sheet: string;
  frames: number;
  fps: number;
  loop: boolean;
  holdLast?: boolean;
  impactFrame?: number;
}

export interface JebManifest {
  frameSize: number;
  scale: number;
  states: Record<JebStateName, JebStateMeta>;
}

export const JEB_MANIFEST: JebManifest = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync(join(JEB_DIR, "manifest.ts"), ts);
console.log(
  `Wrote manifest for ${Object.keys(manifest.states).length} states.`,
);
