// Generates src/renderer/src/assets/<sprite>/manifest.ts from the sprite
// strips in that directory. Every sheet is a horizontal strip of uniform
// frames, so the frame count is width / frameSize read straight from the
// PNG header. Per-state playback metadata (fps, loop, impactFrame) is
// authored here — impactFrame is the synchronization contract between an
// animation and the OS action it decorates.
//
// Usage: node scripts/pack-sprites.js [sprite ...]   (default: all)
// Adding a sprite: drop strips in assets/<id>/, add a SPRITES entry here,
// then write its definition in renderer/src/sprites/<id>/.

const { readFileSync, writeFileSync, readdirSync } = require("node:fs");
const { join, basename } = require("node:path");

const ASSETS_DIR = join(__dirname, "..", "src", "renderer", "src", "assets");

